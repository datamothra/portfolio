#!/bin/sh
# Makes ../DrewAtz_Portfolio.pdf: the index, then each project page, each starting on a new page.
# It builds print.html (every page's <main> in one file) and prints that with headless Chrome.
# Usage: ./make-pdf.sh
#        SITE_URL=https://the.site.address ./make-pdf.sh
# With SITE_URL, links to files on the site (the CV) point at the live site.
# Without it they are left out of the PDF, so no path on this Mac ends up in it.
set -eu
cd "$(dirname "$0")"

CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
PAGES="handoff undertow static hideout triad"
OUT="$(cd .. && pwd)/DrewAtz_Portfolio.pdf"
SITE_URL="${SITE_URL:-}"

if [ ! -x "$CHROME" ]; then
  echo "Google Chrome is not at $CHROME" >&2
  exit 1
fi

for f in index.html $(printf '%s/index.html ' $PAGES); do
  if ! grep -q '^<main>' "$f" || ! grep -q '^</main>' "$f"; then
    echo "$f needs <main> and </main>, each on a line of its own" >&2
    exit 1
  fi
done

# Everything between <main> and </main> in a page.
main_of() {
  sed -n '/^<main>/,/^<\/main>/p' "$1" | sed '1d;$d'
}

# Links between the pages become links inside the PDF.
# Any other link to a file on the site gets SITE_URL in front, or loses its address.
anchors() {
  sed -E -e 's|href="index\.html"|href="#index"|g' \
         -e 's|href="([a-z0-9-]+)/index\.html"|href="#\1"|g' |
  if [ -n "$SITE_URL" ]; then
    sed -E "s|href=\"([^#\":][^\":]*)\"|href=\"${SITE_URL%/}/\\1\"|g"
  else
    sed -E 's| href="[^#":][^":]*"||g'
  fi
}

{
  cat <<'EOF'
<!doctype html>
<!-- Generated by make-pdf.sh. Do not edit: edit the pages and run the script again. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Drew Atz portfolio</title>
<link rel="stylesheet" href="style.css">
</head>
<body>
EOF
  echo '<main class="sheet" id="index">'
  main_of index.html | anchors
  echo '</main>'
  for p in $PAGES; do
    echo "<main class=\"sheet\" id=\"$p\">"
    # project pages sit one folder down, so drop the ../ from their paths
    main_of "$p/index.html" | sed 's|="\.\./|="|g' | anchors
    echo '</main>'
  done
  echo '</body>'
  echo '</html>'
} > print.html

URL="file://$(pwd | sed 's/ /%20/g')/print.html"
PROFILE="$(mktemp -d)"
trap 'rm -rf "$PROFILE"' EXIT

"$CHROME" --headless --disable-gpu --user-data-dir="$PROFILE" \
  --no-pdf-header-footer --print-to-pdf="$OUT" "$URL" 2>/dev/null

if [ ! -s "$OUT" ]; then
  echo "Chrome did not write $OUT" >&2
  exit 1
fi
echo "wrote $OUT"
